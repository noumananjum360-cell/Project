@lru_cache(maxsize=512)
def _render(name: str, color: str, size: int) -> QPixmap:
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round">{PATHS.get(name, "")}</svg>')
    r = QSvgRenderer(QByteArray(svg.encode()))
    img = QImage(size, size, QImage.Format.Format_ARGB32_Premultiplied)
    img.fill(Qt.GlobalColor.transparent)
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    r.render(p, QRectF(0, 0, size, size))
    p.end()
    return QPixmap.fromImage(img)


def icon(name: str, color: str | None = None, size: int = 40) -> QIcon:
    return QIcon(_render(name, color or theme.c("text"), size))


def pixmap(name: str, color: str | None = None, size: int = 20) -> QPixmap:
    return _render(name, color or theme.c("text"), size)
